const icons = new Set(PROJECT_ICONS)
export function projectAppearance(project: { icon?: string | null; color?: string | null }) {
  const icon = project.icon && icons.has(project.icon) ? project.icon : DEFAULT_PROJECT_ICON
  const color =
    project.color && /^#[0-9a-f]{6}$/i.test(project.color) ? project.color : DEFAULT_PROJECT_COLOR
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(color.slice(i, i + 2), 16))
  return { icon, color, tint: `rgba(${r}, ${g}, ${b}, 0.1)` }
}
